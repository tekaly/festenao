import 'dart:io';

import 'package:dev_build/menu/menu.dart';
import 'package:tekartik_firebase_build/firebase_project_menu.dart';
import 'package:tkcms_common/tkcms_flavor.dart';

/// The dart functions of an app, dev and prod: what its build menu offers
/// ([menuFestenaoFunctionsContent]) and its deploy chain
/// ([deployDevTestThenProd]).
class FestenaoFunctionsBuild {
  /// The dev project: its functions, and the firebase project menu.
  final FirebaseProjectBuilder dev;

  /// The prod project (its functions).
  final FirebaseProjectBuilder prod;

  /// Runs the rest tests of the deployed functions of a flavor (the
  /// deployed version included); throws when one fails.
  final Future<void> Function(FlavorContext flavorContext) restTests;

  /// Bumps the version of the functions package, null when it has none.
  final Future<void> Function()? bumpVersion;

  /// Shows the deployed versions (the server info), null when not offered.
  final Future<void> Function()? serverInfo;

  /// The functions of the [dev] and [prod] projects, checked by
  /// [restTests]; [bumpVersion] and [serverInfo] add their items to the
  /// menu.
  const FestenaoFunctionsBuild({
    required this.dev,
    required this.prod,
    required this.restTests,
    this.bumpVersion,
    this.serverInfo,
  });

  /// Deploys the dev functions, runs the dev rest tests, then, only when
  /// they pass, deploys the prod functions and runs the prod rest tests.
  /// Any failure (deploy or test) throws and stops the chain.
  Future<void> deployDevTestThenProd() async {
    stdout.writeln('# deploying dev functions');
    await dev.deployFunctions();
    stdout.writeln('# running dev rest tests');
    await restTests(FlavorContext.dev);
    stdout.writeln('# deploying prod functions');
    await prod.deployFunctions();
    stdout.writeln('# running prod rest tests');
    await restTests(FlavorContext.prod);
  }
}

/// Declares the items of the dart functions of [functions] in the current
/// menu: the version bump and the deploy chain with a bump first (when
/// [FestenaoFunctionsBuild.bumpVersion]), the deploy chain, the server info
/// (when [FestenaoFunctionsBuild.serverInfo]), the local compile, the deploy
/// and the rest tests of each flavor, and the firebase project menu of the
/// dev project.
void menuFestenaoFunctionsContent(FestenaoFunctionsBuild functions) {
  var bumpVersion = functions.bumpVersion;
  if (bumpVersion != null) {
    item('bump version (functions)', bumpVersion);
  }
  item(
    'deploy dev, rest test dev, then deploy and test prod',
    functions.deployDevTestThenProd,
  );
  if (bumpVersion != null) {
    item(
      'bump version, deploy dev, rest test dev, then deploy and test prod',
      () async {
        await bumpVersion();
        await functions.deployDevTestThenProd();
      },
    );
  }
  var serverInfo = functions.serverInfo;
  if (serverInfo != null) {
    item('server info (deployed versions)', serverInfo);
  }
  item('compile (local check)', () => functions.dev.compileFunctions());
  item('deploy dev functions', () => functions.dev.deployFunctions());
  item('rest test dev', () => functions.restTests(FlavorContext.dev));
  item('deploy prod functions', () => functions.prod.deployFunctions());
  item('rest test prod', () => functions.restTests(FlavorContext.prod));
  menu('firebase project', () {
    menuFirebaseProjectBuilderContent(builder: functions.dev);
  });
}

/// Declares the items of the rules of an app in the current menu:
/// [generateFirestoreRules] (the file [firestoreRulesFile], for the label),
/// then the same followed by the deploy of the rules and indexes of
/// [project]; the storage rules generated by [generateStorageRules] and
/// deployed, and the storage CORS applied by [applyStorageCors] (generated
/// and set with gcloud), when given.
void menuFestenaoRulesContent({
  required FirebaseProjectBuilder project,
  required String firestoreRulesFile,
  required Future<void> Function() generateFirestoreRules,
  Future<void> Function()? generateStorageRules,
  Future<void> Function()? applyStorageCors,
}) {
  item('generate $firestoreRulesFile', generateFirestoreRules);
  item('generate and deploy rules and indexes', () async {
    await generateFirestoreRules();
    await project.deployFirestore();
  });
  if (generateStorageRules != null) {
    item('generate and deploy the storage rules', () async {
      await generateStorageRules();
      await project.deployStorageRules();
    });
  }
  if (applyStorageCors != null) {
    item('generate and apply the storage CORS (gcloud)', applyStorageCors);
  }
}
